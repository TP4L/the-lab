"""Pack THE LAB coach docs into public/graphics/knowledge.js for the studio's AI writer.
Run after editing anything in .claude/skills/lab-coach/."""
import json, pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
skill = root / '.claude/skills/lab-coach'
def body(p):
    t = p.read_text()
    return re.sub(r'^---\n.*?\n---\n', '', t, flags=re.S).strip()
k = {
    'engine': body(skill / 'SKILL.md'),
    'vocabulary': body(skill / 'reference/vocabulary.md'),
}
out = root / 'public/graphics/knowledge.js'
out.write_text('/* Generated by tools/build-knowledge.py — do not edit by hand. */\nwindow.LAB_KNOWLEDGE = ' + json.dumps(k, indent=1) + ';\n')
print(out, out.stat().st_size)
