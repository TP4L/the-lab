'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {start,staff}=require('./helpers.js');
async function player(server,coach,name,needs) {
  const made=(await coach.post('/api/athletes',{name,focus:name+' cue'})).body;
  const member=server.client();
  await member.signup(name,name+'@lab.test');
  await member.post('/api/claim',{code:made.claim_code});
  await coach.put('/api/athletes/'+made.athlete.id,{training_needs:needs});
  return {id:made.athlete.id,member};
}
test('a planned group lesson carries real players, drills and private cues from brief to recap',async t=>{
  const server=await start();t.after(server.close);
  const {coach,coach2}=await staff(server);
  const a=await player(server,coach,'North',['read the bounce']);
  const b=await player(server,coach,'South',['bounce reads']);
  const plan=(await coach.post('/api/plans',{title:'Kitchen entry',starts_at:new Date(Date.now()+86400000).toISOString(),
    blocks:[{drill:'Pitch and Catch',instructions:'Wait for the bounce'},{drill:'Hold the line'}],players:[{athlete_id:a.id},{athlete_id:b.id},{name:'Guest'}]})).body;
  const brief='/api/plans/'+plan.id+'/lesson';
  assert.equal((await coach2.get(brief)).status,404);
  const next=(await coach.get('/api/coach/next-lesson')).body.lesson;
  assert.equal(next.plan.id,plan.id);
  assert.deepEqual(next.shared,[['Bounce read',['North','South']]]);
  const req={source_plan_id:plan.id,plan_version:plan.version,id:randomUUID(),athletes:[a.id,b.id],blocks:plan.blocks.map(x=>x.id).reverse()};
  assert.equal((await coach.post('/api/training/sessions',{...req,plan_version:0})).status,409);
  const first=await coach.post('/api/training/sessions',req);
  assert.equal(first.status,201);
  assert.deepEqual(first.body.items.map(x=>x.name),['Pitch and Catch','Hold the line']);
  const url='/api/training/sessions/'+first.body.id;
  assert.equal((await coach.post('/api/training/sessions',{...req,id:randomUUID()})).body.id,first.body.id);
  assert.equal((await coach.get('/api/coach/next-lesson')).body.live.id,first.body.id);
  assert.equal(first.body.athletes[0].lesson_cue,'North cue');
  assert.deepEqual((await a.member.get(url)).body.athletes.map(x=>x.name),['North']);
  assert.equal((await coach.put(url,{version:1,status:'complete'})).status,200);
  assert.equal((await coach.get(brief)).body.session.status,'complete');
  assert.equal((await coach.get('/api/plans/'+plan.id)).body.status,'done');
  assert.equal((await coach.get('/api/coach/next-lesson')).body.lesson,undefined);
});
test('score, repeat, record transfer and advance one athlete without moving teammates',async t=>{
  const server=await start();t.after(server.close);
  const {coach,coach2}=await staff(server);
  const a=await player(server,coach,'East',[]), b=await player(server,coach,'West',[]);
  const req={client_key:randomUUID(),title:'Own the transition',goal:'Earn a balanced entry',start_day:'2026-11-05',athletes:[a.id,b.id],
    steps:['Read','Enter'].map(title=>({title,practice:'Wait',target:'7/10',setup:'Ten feeds',minutes:12}))};
  assert.equal((await coach2.post('/api/coach/programs',req)).status,403);
  const response=await coach.post('/api/coach/programs',req);
  assert.equal(response.status,201);
  assert.equal((await coach.post('/api/coach/programs',req)).body.id,response.body.id);
  const mine=async p=>(await p.member.get('/api/me/programs')).body[0].blocks;
  const blocks=await mine(a),url='/api/development-blocks/'+blocks[0].id;
  assert.equal(blocks.length,1);
  assert.equal((await b.member.get(url)).status,404);
  assert.equal((await b.member.post(url+'/observations',{client_key:randomUUID(),body:'No access'})).status,404);
  const session=(await coach.post('/api/training/sessions',{id:randomUUID(),title:'Two-player lesson',athletes:[a.id,b.id],items:[{name:'Ten resets',measure:'reps'}]})).body;
  const sessionUrl='/api/training/sessions/'+session.id;
  const resultPath=sessionUrl+'/program-result';
  const checkpoint={athlete_id:a.id,block_id:blocks[0].id,item_idx:0,cue:'Start one step deeper'};
  assert.equal((await coach.post(resultPath,checkpoint)).status,409);
  await coach.put(sessionUrl,{version:1,status:'complete'});
  assert.equal((await coach.post(resultPath,checkpoint)).status,200);
  assert.equal((await coach.post(resultPath,checkpoint)).status,200);
  assert.equal((await coach.post(resultPath,{...checkpoint,athlete_id:b.id})).status,404);
  assert.equal((await b.member.post(resultPath,checkpoint)).status,404);
  const ev={id:randomUUID(),item_idx:0,athlete_id:a.id,kind:'make',at:new Date().toISOString()};
  assert.equal((await coach.post(sessionUrl+'/events',{events:[ev]})).status,200);
  const saved=(await a.member.get(url)).body.checkpoints;
  assert.equal(saved.length,1);assert.equal(saved[0].makes,1);assert.equal(saved[0].attempts,1);assert.equal(saved[0].cue,checkpoint.cue);
  const evidence={status:'evidence_submitted',attempt_id:randomUUID(),makes:0,attempts:10,game_makes:1,game_attempts:2,conditions:'Ten feeds'};
  assert.equal((await a.member.put(url,{...evidence,makes:11})).status,400);
  const result=await a.member.put(url,evidence);
  assert.equal(result.status,200);
  assert.equal(result.body.status,'evidence_submitted');
  assert.equal(result.body.attempts[0].makes,0);
  assert.equal((await a.member.put(url,evidence)).body.attempts.length,1);
  assert.equal((await coach.put(url,{status:'ready_retest',coach_feedback:'Wait longer.'})).status,200);
  assert.equal((await mine(a)).length,1);
  const retest=await a.member.put(url,{...evidence,attempt_id:randomUUID(),makes:7});
  assert.equal(retest.body.attempts.length,2);
  const observation={body:'I waited for the bounce in doubles.',client_key:randomUUID(),makes:2,attempts:4};
  await a.member.post(url+'/observations',observation);
  await a.member.post(url+'/observations',observation);
  assert.equal((await coach.get(url)).body.observations.length,1);
  assert.equal((await coach.put(url,{status:'mastered',coach_feedback:'Take the entry on balance.'})).status,200);
  const advanced=await mine(a);
  assert.equal(advanced.length,2); assert.equal((await mine(b)).length,1);
  assert.equal((await a.member.get('/api/development-blocks/'+advanced[1].id)).body.previous_feedback,'Take the entry on balance.');
  assert.equal((await coach.put(url,{status:'ready_retest'})).status,409);
  assert.equal((await coach2.get('/api/coach/programs')).body.length,0);
});
