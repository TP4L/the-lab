'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const {start,staff,uid}=require('./helpers');
test('signed event handoff links returning athletes and guests, reopens the same lesson and scopes individual recaps',async t=>{
  const {publicKey,privateKey}=crypto.generateKeyPairSync('ec',{namedCurve:'P-256'});
  const s=await start({invitationalsPublicKey:publicKey.export({format:'jwk'})});t.after(s.close);
  const {coach,coach2}=await staff(s),anon=s.client(),member=s.client(),other=s.client();
  const profile=(await coach.post('/api/athletes',{name:'Ari'})).body;
  const aid=profile.athlete.id;
  await member.signup('Ari','ari@lab.test');await member.post('/api/claim',{code:profile.claim_code});
  await other.signup('Unrelated','unrelated@lab.test');
  const key='a'.repeat(64),guest='b'.repeat(64),newKey='c'.repeat(64);
  const roster=[{key,name:'Ari',court:'Court 1',arrival:'Checked in'},{key:guest,name:'Guest',court:'Court 1',arrival:'Expected'},{key:newKey,name:'Jordan',court:'Court 2',arrival:'Expected'}];
  const ev={id:'event-test',title:'Friday reset clinic',starts_at:'2026-11-07T01:00:00.000Z',sport:'Pickleball',location:'City Centre',courts:2,minutes:80,plan:'Pitch & Catch\nRead the bounce before you move.\n\nBack to the kitchen'};
  const packet=(fields={})=>{const payload=JSON.stringify({iss:'lab-invitationals',aud:'lab-companion',type:'lesson',nonce:uid(),iat:Date.now(),coach:'coach@lab.test',revision:1,event:ev,roster,...fields});return {payload,signature:crypto.sign('sha256',Buffer.from(payload),{key:privateKey,dsaEncoding:'ieee-p1363'}).toString('hex')};};
  const receive=p=>anon.post('/api/invitationals/receive',p);
  const initial=packet(),tampered={...initial,payload:initial.payload.replace('City Centre','other')};
  assert.equal((await receive(tampered)).status,403);
  assert.equal((await receive(packet({iat:Date.now()-200000}))).status,400);
  assert.deepEqual((await receive(packet({type:'connection'}))).body,{connected:true});
  const ticket=(await receive(initial)).body.ticket;
  assert.equal((await receive(initial)).status,409);
  const url='/api/invitationals/open/'+ticket;
  assert.equal((await anon.get(url)).status,401);
  assert.equal((await coach2.get(url)).status,403);
  assert.equal((await member.get(url)).status,403);
  assert.equal((await coach.get(url)).body.roster.length,3);
  const confirm={group:1,players:[{key,athlete:aid},{key:guest,athlete:null}],expected_version:0};
  assert.equal((await coach.post(url,{...confirm,players:[{key:'f'.repeat(64),athlete:aid}]})).status,400);
  const created=await coach.post(url,confirm);assert.equal(created.status,200,JSON.stringify(created.body));
  const pid=created.body.plan_id;
  assert.equal((await coach.post(url,confirm)).body.plan_id,pid);
  const initialBrief=(await coach.get('/api/plans/'+pid+'/lesson')).body;
  assert.deepEqual(initialBrief.blocks.map(b=>b.drill),['Pitch & Catch','Back to the kitchen']);
  assert.equal(initialBrief.players.find(p=>p.name==='Guest').eligible,false);
  const newer=(await receive(packet({revision:2,roster:[{...roster[0],arrival:'Running late'},roster[2]]}))).body.ticket;
  const fresh='/api/invitationals/open/'+newer;
  assert.equal((await coach.get(url)).status,409);
  const reopened=(await coach.get(fresh)).body;
  assert.equal(reopened.roster[0].athlete_id,aid);
  assert.equal(reopened.groups[0].plan_id,pid);
  const updated=await coach.post(fresh,{group:1,players:[{key,athlete:aid}],expected_version:reopened.groups[0].version});
  assert.equal(updated.body.plan_id,pid);
  const second=await coach.post(fresh,{group:2,players:[{key:newKey,athlete:'new'}],expected_version:0});
  assert.notEqual(second.body.plan_id,pid);assert.ok(second.body.plan_id);
  assert.equal((await coach.post(fresh,{group:3,players:Array(9).fill({key,athlete:aid})})).status,400);
  const brief=(await coach.get('/api/plans/'+pid+'/lesson')).body;
  assert.equal(brief.players.find(p=>p.id===aid).arrival,'Running late');
  assert.equal(brief.players.find(p=>p.name==='Guest').rsvp,'out');
  const score='/api/training/sessions', live=(await coach.post(score,{source_plan_id:pid,plan_version:brief.plan.version,id:uid(),athletes:[aid],blocks:[brief.blocks[0].id]})).body;
  const p={group:1,players:[{key,athlete:aid}],expected_version:brief.plan.version};
  assert.equal((await coach.post(fresh,p)).body.session_id,live.id);
  const recap='/api/me/invitationals/event-test';
  assert.equal((await member.get(recap)).body.sessions.length,0);
  await coach.put(score+'/'+live.id,{version:1,status:'complete'});
  assert.equal((await member.get(recap)).body.sessions[0].id,live.id);
  assert.equal((await other.get(recap)).body.sessions.length,0);
  assert.equal((await coach.post(fresh,p)).body.session_status,'complete');
  const returning=(await receive(packet({revision:4,event:{...ev,id:'next-event'}}))).body.ticket;
  assert.equal((await coach.get('/api/invitationals/open/'+returning)).body.roster[0].athlete_id,aid);
  const wrongCoach=(await receive(packet({coach:'coach2@lab.test',revision:3}))).body.ticket;
  const wrong='/api/invitationals/open/'+wrongCoach;
  assert.equal((await coach2.get(wrong)).body.groups.find(x=>x.group_num===1).other_coach,true);
  assert.equal((await coach2.post(wrong,p)).status,403);
});
